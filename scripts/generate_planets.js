      const t = (idx / 100) * Math.PI * 5.6; // spiral angle
      const r = 7.5 + Math.pow(idx / 100, 0.76) * 62.0; // radius from 7.5 to ~70 units
      const angle = t + (arm * Math.PI);
      const noiseX = Math.sin(idx * 13.7) * 2.2;
      const noiseZ = Math.cos(idx * 17.3) * 2.2;
      const noiseY = (Math.sin(idx * 6.3) * 4.2) + (Math.cos(t) * 1.8);
      const x = Number((Math.cos(angle) * r + noiseX).toFixed(2));
      const z = Number((Math.sin(angle) * r + noiseZ).toFixed(2));
      const y = Number(noiseY.toFixed(2));
      coords = [x, y, z];
